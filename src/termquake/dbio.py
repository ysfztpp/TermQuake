"""The database's canonical text form: data/db/<table>.sql.

The SQL database is the source of truth. It is stored in git as one file per
table, one INSERT statement per row, ordered by primary key. That gives:

* readable diffs: every change to a term is a one-line change in term.sql,
  reviewable in a pull request;
* full history: `git log -p data/db/term.sql`;
* plain SQL: the files load into SQLite as they are, and into PostgreSQL with
  the same schema (phase 2).

`dump` writes the files from a database; `load` fills an empty database from
them. load(dump(db)) == db, and CI checks that the committed files are exactly
what `dump` produces.

Derived data is not stored: the qa_issue table and the term.text_norm column
are recomputed on every build, so a hand edit of a term in GitHub never leaves
a stale search key behind.
"""

from __future__ import annotations

import hashlib
import sqlite3
from pathlib import Path

# Dump/load order respects foreign keys.
TABLES = [
    "language",
    "domain",
    "domain_label",
    "source",
    "contributor",
    "concept",
    "definition",
    "term",
    "context",
    "figure",
    "concept_relation",
    "review_vote",
    "revision",
    "import_batch",
    "data_release",
]

# Columns computed by the build (see build.refresh_search_keys); never written to data/db.
DERIVED_COLUMNS = {"term": {"text_norm"}}

HEADER = (
    "-- TermQuake canonical data: table {table}. Generated by `termquake dump`; do not reformat.\n"
)


def _literal(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, bytes):
        return "X'" + value.hex() + "'"
    text = str(value).replace("'", "''")
    # Keep one row per line: line breaks inside values are written as SQL char()
    # calls, exactly (\r\n stays \r\n, a lone \r stays \r).
    if "\n" in text or "\r" in text:
        parts: list[str] = []
        current = ""
        for ch in text:
            if ch in "\r\n":
                parts.append(f"'{current}'")
                parts.append(f"char({ord(ch)})")
                current = ""
            else:
                current += ch
        parts.append(f"'{current}'")
        return " || ".join(parts)
    return f"'{text}'"


def _primary_key(conn: sqlite3.Connection, table: str) -> list[str]:
    cols = conn.execute(f"PRAGMA table_info({table})").fetchall()
    pk = [c[1] for c in sorted(cols, key=lambda c: c[5]) if c[5] > 0]
    return pk or [c[1] for c in cols]


def dump_table(conn: sqlite3.Connection, table: str) -> str:
    derived = DERIVED_COLUMNS.get(table, set())
    columns = [c[1] for c in conn.execute(f"PRAGMA table_info({table})") if c[1] not in derived]
    order = ", ".join(_primary_key(conn, table))
    col_list = ", ".join(columns)
    lines = [HEADER.format(table=table)]
    for row in conn.execute(f"SELECT {col_list} FROM {table} ORDER BY {order}"):
        values = ", ".join(_literal(v) for v in row)
        lines.append(f"INSERT INTO {table} ({col_list}) VALUES ({values});\n")
    return "".join(lines)


def dump_texts(conn: sqlite3.Connection) -> dict[str, str]:
    """{filename: text} exactly as `dump` would write them."""
    return {f"{table}.sql": dump_table(conn, table) for table in TABLES}


def digest(texts: dict[str, str]) -> str:
    """Fingerprint of a set of data files (name + content)."""
    h = hashlib.sha256()
    for name in sorted(texts):
        h.update(name.encode())
        h.update(b"\0")
        h.update(texts[name].encode("utf-8"))
        h.update(b"\0")
    return h.hexdigest()


def read_texts(in_dir: Path) -> dict[str, str]:
    """{filename: text} of the data files on disk (missing files are left out)."""
    return {
        f"{t}.sql": (in_dir / f"{t}.sql").read_text(encoding="utf-8")
        for t in TABLES
        if (in_dir / f"{t}.sql").exists()
    }


def dump(conn: sqlite3.Connection, out_dir: Path) -> dict[str, str]:
    """Write every table to out_dir/<table>.sql. Returns {filename: text}."""
    out_dir.mkdir(parents=True, exist_ok=True)
    files = dump_texts(conn)
    for name, text in files.items():
        # Always LF, also on Windows, so files stay byte-identical across platforms.
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
    return files


def diff(conn: sqlite3.Connection, out_dir: Path) -> list[str]:
    """Names of files whose content differs from what `dump` would write."""
    on_disk = read_texts(out_dir)
    return [name for name, text in dump_texts(conn).items() if on_disk.get(name) != text]


class DataFileError(ValueError):
    """A data file cannot be loaded (bad SQL, a broken constraint)."""


def load(conn: sqlite3.Connection, in_dir: Path) -> None:
    """Fill an empty database (schema already created) from in_dir/<table>.sql.

    Foreign keys are switched off while loading, so a row may refer to a row
    that comes later (e.g. concept.merged_into); the caller checks them all
    afterwards with PRAGMA foreign_key_check.
    """
    missing = [t for t in TABLES if not (in_dir / f"{t}.sql").exists()]
    if missing:
        raise FileNotFoundError(
            f"{in_dir} is missing {', '.join(m + '.sql' for m in missing)}. "
            "Run `termquake migrate` once to create the database from the legacy sheet."
        )
    conn.execute("PRAGMA foreign_keys = OFF")
    try:
        for table in TABLES:
            sql = (in_dir / f"{table}.sql").read_text(encoding="utf-8")
            try:
                conn.executescript(f"BEGIN;\n{sql}\nCOMMIT;")
            except sqlite3.Error as exc:
                if conn.in_transaction:
                    conn.rollback()
                raise DataFileError(f"data/db/{table}.sql: {exc}") from exc
    finally:
        conn.execute("PRAGMA foreign_keys = ON")
