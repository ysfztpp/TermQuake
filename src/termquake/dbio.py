"""The database's canonical text form: data/db/<table>.sql.

The SQL database is the source of truth. It is stored in git as one file per
table, one INSERT statement per row, ordered by primary key. That gives:

* readable diffs: every change to a term is a one-line change in term.sql,
  reviewable in a pull request;
* full history: `git log -p data/db/term.sql`;
* plain SQL: the files load into SQLite as they are, and into PostgreSQL with
  the same schema (phase 2).

`dump` writes the files from a database; `load` fills an empty database from
them. load(dump(db)) == db, and CI checks that the committed files are exactly
what `dump` produces.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path

# Dump/load order respects foreign keys. Derived tables are not stored:
#   qa_issue   is recomputed from the data on every build (qa.py);
#   import_raw is the legacy sheet archive, kept as CSV in data/legacy/.
TABLES = [
    "language",
    "domain",
    "domain_label",
    "source",
    "contributor",
    "concept",
    "definition",
    "term",
    "context",
    "figure",
    "concept_relation",
    "review_vote",
    "revision",
    "import_batch",
    "data_release",
]

HEADER = (
    "-- TermQuake canonical data: table {table}. Generated by `termquake dump`; do not reformat.\n"
)


def _literal(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, bytes):
        return "X'" + value.hex() + "'"
    text = str(value).replace("'", "''")
    # Keep one row per line: newlines inside values are written as SQL char() calls.
    if "\n" in text or "\r" in text:
        parts = text.replace("\r\n", "\n").split("\n")
        return " || char(10) || ".join(f"'{p}'" for p in parts)
    return f"'{text}'"


def _primary_key(conn: sqlite3.Connection, table: str) -> list[str]:
    cols = conn.execute(f"PRAGMA table_info({table})").fetchall()
    pk = [c[1] for c in sorted(cols, key=lambda c: c[5]) if c[5] > 0]
    return pk or [c[1] for c in cols]


def dump_table(conn: sqlite3.Connection, table: str) -> str:
    columns = [c[1] for c in conn.execute(f"PRAGMA table_info({table})")]
    order = ", ".join(_primary_key(conn, table))
    col_list = ", ".join(columns)
    lines = [HEADER.format(table=table)]
    for row in conn.execute(f"SELECT {col_list} FROM {table} ORDER BY {order}"):
        values = ", ".join(_literal(v) for v in row)
        lines.append(f"INSERT INTO {table} ({col_list}) VALUES ({values});\n")
    return "".join(lines)


def dump(conn: sqlite3.Connection, out_dir: Path) -> dict[str, str]:
    """Write every table to out_dir/<table>.sql. Returns {filename: text}."""
    out_dir.mkdir(parents=True, exist_ok=True)
    files = {f"{table}.sql": dump_table(conn, table) for table in TABLES}
    for name, text in files.items():
        (out_dir / name).write_text(text, encoding="utf-8")
    return files


def diff(conn: sqlite3.Connection, out_dir: Path) -> list[str]:
    """Names of files whose content differs from what `dump` would write."""
    stale = []
    for table in TABLES:
        path = out_dir / f"{table}.sql"
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != dump_table(conn, table):
            stale.append(path.name)
    return stale


def load(conn: sqlite3.Connection, in_dir: Path) -> None:
    """Fill an empty database (schema already created) from in_dir/<table>.sql."""
    missing = [t for t in TABLES if not (in_dir / f"{t}.sql").exists()]
    if missing:
        raise FileNotFoundError(
            f"{in_dir} is missing {', '.join(m + '.sql' for m in missing)}. "
            "Run `termquake migrate` once to create the database from the legacy sheet."
        )
    for table in TABLES:
        sql = (in_dir / f"{table}.sql").read_text(encoding="utf-8")
        conn.executescript(f"BEGIN;\n{sql}\nCOMMIT;")
